#!/usr/bin/env python
"""Visualize Agent4TS results.

Reads results/<kind>/ and renders summary figures + a static HTML index into
vis/generated/ (gitignored). Run via scripts or directly:

    conda run -n tim python vis/plot_results.py --kind smoke
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]


def plot_benchmark(kind_dir: Path, out: Path) -> list[Path]:
    f = kind_dir / "benchmark" / "benchmark.json"
    if not f.exists():
        return []
    data = json.loads(f.read_text())
    figs = []
    for task, models in data.items():
        if not isinstance(models, dict) or "status" in models:
            continue
        names, vals = [], []
        for m, r in sorted(models.items()):
            v = (r.get("metrics") or {}).get("normalized_mae")
            if v is not None:
                names.append(m); vals.append(v)
        if not names:
            continue
        fig, ax = plt.subplots(figsize=(6, 3), dpi=110)
        ax.barh(names, vals, color="#4878a8")
        ax.set_xlabel("normalized MAE (lower = better)")
        ax.set_title(f"benchmark — {task}")
        ax.grid(alpha=0.3, axis="x")
        p = out / f"benchmark_{task}.png"
        fig.tight_layout(); fig.savefig(p); plt.close(fig)
        figs.append(p)
    return figs


def plot_search(kind_dir: Path, out: Path) -> list[Path]:
    f = kind_dir / "search" / "search_all.json"
    if not f.exists():
        return []
    data = json.loads(f.read_text())
    figs = []
    for run_key, run in data.items():
        if not isinstance(run, dict) or "history" not in run:
            continue
        hist = run["history"]
        if not hist:
            continue
        xs = [h["round"] for h in hist]
        ys = [h["normalized_mae"] for h in hist]
        acc = [h["accepted"] for h in hist]
        fig, ax = plt.subplots(figsize=(6, 3), dpi=110)
        ax.plot(xs, ys, "-o", color="#777", ms=4, label="candidate")
        for x, y, a in zip(xs, ys, acc):
            if a and y is not None:
                ax.scatter([x], [y], color="#2ca02c", zorder=3, label=None)
        if run.get("f0_metric") is not None:
            ax.axhline(run["f0_metric"], color="#d62728", ls="--", lw=1, label="f0")
        ax.set_xlabel("round"); ax.set_ylabel("normalized MAE")
        ax.set_title(f"search — {run_key} (green=accepted)")
        ax.legend(fontsize=7); ax.grid(alpha=0.3)
        p = out / f"search_{run_key}.png"
        fig.tight_layout(); fig.savefig(p); plt.close(fig)
        figs.append(p)
    return figs


def plot_degradation(kind_dir: Path, out: Path) -> list[Path]:
    figs = []
    for f in (kind_dir / "degradation").rglob("degradation.json") if (kind_dir / "degradation").exists() else []:
        rows = json.loads(f.read_text())
        tags = [r["tag"] for r in rows if r["normalized_mae"] is not None]
        vals = [r["normalized_mae"] for r in rows if r["normalized_mae"] is not None]
        if not tags:
            continue
        fig, ax = plt.subplots(figsize=(6, 3), dpi=110)
        colors = ["#2ca02c" if t == "none" else "#4878a8" for t in tags]
        ax.bar(tags, vals, color=colors)
        ax.set_ylabel("normalized MAE"); ax.set_title(f"degradation — {f.parent.name}")
        ax.grid(alpha=0.3, axis="y"); plt.xticks(rotation=30, fontsize=7)
        p = out / f"degradation_{f.parent.name}.png"
        fig.tight_layout(); fig.savefig(p); plt.close(fig)
        figs.append(p)
    return figs


def make_index(figs: list[Path], out: Path, kind: str) -> Path:
    items = "\n".join(
        f'<div class="card"><h3>{p.stem}</h3><img src="{p.name}" /></div>' for p in figs
    )
    html = f"""<!doctype html><html><head><meta charset="utf-8">
<title>Agent4TS vis — {kind}</title>
<style>
 body {{ font-family: sans-serif; background:#fafafa; margin:2rem; }}
 .card {{ background:#fff; border:1px solid #ddd; border-radius:8px;
          padding:1rem; margin:1rem 0; max-width:720px; }}
 img {{ max-width:100%; }}
 h1 {{ color:#333; }}
</style></head><body>
<h1>Agent4TS results — {kind}</h1>
<p>{len(figs)} figures. Generated by vis/plot_results.py.</p>
{items}
</body></html>"""
    idx = out / "index.html"
    idx.write_text(html, encoding="utf-8")
    return idx


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--kind", default="smoke", help="results sub-folder to visualize")
    a = ap.parse_args()
    kind_dir = ROOT / "results" / a.kind
    out = ROOT / "vis" / "generated" / a.kind
    out.mkdir(parents=True, exist_ok=True)
    figs = []
    figs += plot_benchmark(kind_dir, out)
    figs += plot_search(kind_dir, out)
    figs += plot_degradation(kind_dir, out)
    idx = make_index(figs, out, a.kind)
    print(f"{len(figs)} figures -> {idx}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
